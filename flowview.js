export const DEFAULT_THEME = "modern-ember";

export function applyTheme(id) {
  const themeId = Object.hasOwn(THEMES, id) ? id : DEFAULT_THEME;
  const root = document.documentElement;
  for (const t of Object.keys(THEMES)) root.classList.remove("theme-" + t);
  root.classList.add("theme-" + themeId);
  root.setAttribute("data-node-theme", themeId);
  root.style.setProperty("--app-font-family", THEMES[themeId].font);
  return themeId;
}

let SNAP = null;
let unitTemplate = null;

export async function loadSnapshot() {
  if (SNAP) return SNAP;
  const res = await fetch("/snapshot/snapshot.html", {cache: "no-store"}); // generated by build-snapshot.js: no style="" attributes, no <style> blocks
  if (!res.ok) throw new Error("snapshot");
  const doc = new DOMParser().parseFromString(await res.text(), "text/html");
  const tpl = (id) => doc.getElementById(id);
  const meta = tpl("snap-meta");
  SNAP = {
    htmlStyle: meta.dataset.htmlStyle,
    bodyClass: meta.dataset.bodyClass
      .split(/\s+/)
      .filter((c) => !["fj-bg-idle", "fj-ambient-freeze"].includes(c))
      .join(" "),
    html: ["snap-topbar", "snap-headerBg", "snap-container", "snap-footer"].map((id) => tpl(id).innerHTML).join("\n")
  };
  return SNAP;
}

// The app's root variables and body classes (radii, density, tokens). Needed by every screen, including the entry dialog.
export function prepareChrome() {
  applyDeclarations(document.documentElement, SNAP.htmlStyle); // CSSOM, not a style attribute (strict CSP)
  document.body.className = SNAP.bodyClass;
}

export function mountApp() {
  $("#snapRoot").innerHTML = SNAP.html; // a static, trusted file from this repo: no person's text is ever parsed as HTML
  const first = $(".enum-image-unit");
  unitTemplate = first ? first.cloneNode(true) : null;
  // The snapshot is a frozen demo Flow: wipe every piece of its demo content before anything is shown.
  $("#tree ul")?.replaceChildren();
  $(".image-gallery")
    ?.querySelectorAll(".enum-image-unit")
    .forEach((u) => u.remove());
  const tw = $("#tree-title");
  if (tw) {
    tw.value = "";
    tw.setAttribute("readonly", "");
  }
}

// ---- guest view: hide what a guest does not get; dim what a View guest cannot do -----------------------------------
const hideEl = (e) => {
  if (!e) return;
  e.hidden = true;
  e.style.setProperty("display", "none", "important");
};
function lock(e, tip) {
  if (!e) return;
  e.classList.add("cx-locked");
  e.setAttribute("aria-disabled", "true");
  e.setAttribute("data-cx-tooltip", tip);
}
function unlock(e) {
  if (!e) return;
  e.classList.remove("cx-locked");
  e.removeAttribute("aria-disabled");
  e.removeAttribute("data-cx-tooltip");
}

// Dims (View) or frees (Edit) the controls a View guest cannot use. Runs on EVERY render, so a role change in either direction
// (the owner downgrades or upgrades this guest) takes effect without a reload; the tip also follows the owner's name.
export function applyRoleLocks(S) {
  const viewTip = `You can view this Flow. Ask ${S.ownerName ? iso(S.ownerName) : "the owner"} for edit access`;
  const set = (e) => (S.role === "view" ? lock(e, viewTip) : unlock(e));
  for (const sel of ["#tree-add-node-btn", "#tree-add-image-btn", "#tree-delete-node-btn", "#delete-all-images", ".canvas-add-slot-btn"]) set($(sel));
  // A top-level node can only be added by the owner (the owner refuses it for every guest), so this stays dimmed for Edit guests too.
  lock($("#add-root"), S.role === "view" ? viewTip : "Only the owner can add a top-level node");
  for (const b of $$(".canvas-rail-add-btn, .canvas-rail-copy-btn, .canvas-rail-stack-btn, .canvas-rail-delete-btn, .gallery-tags-manager-btn")) set(b);
}

export function guestify(S) {
  S.presenceHost = $("#header-unsaved-indicator")?.parentElement || $(".topbar");
  for (const sel of ["#header-unsaved-indicator", "#file-menu-wrapper"]) hideEl($(sel));
  for (const sel of ["#cache-bust-btn", "#browser-btn", "#terminal-btn"]) {
    const b = $(sel);
    hideEl(b && (b.closest(".tooltip-wrapper") || b));
  }
  hideEl($(".topbar-settings-group"));
  for (const b of $$(".app-rail-item")) if (!["app-rail-flow-btn", "app-rail-joe-btn", "app-rail-docs-btn"].includes(b.id)) hideEl(b);
  wireDocs(); // G8
  for (const e of $$(".breadcrumb-storage-figure, .status-footer-scheduler")) hideEl(e);
  applyRoleLocks(S);
  // Add-a-slot (media) belongs to T4c; add/delete node are wired by edit.js for Edit guests.
  for (const sel of ["#tree-add-image-btn"]) $(sel)?.setAttribute("data-cx-slice", "t4c");
}

// The app renders tooltips through one body portal (.flowjoe-tooltip); a minimal stand-in for the locked controls.
export function wireTooltips() {
  const cxTip = el("div", {cls: "flowjoe-tooltip", attrs: {role: "tooltip"}});
  cxTip.appendChild(el("span", {cls: "cx-tip-text"}));
  document.body.appendChild(cxTip);
  const show = (target) => {
    cxTip.querySelector(".cx-tip-text").textContent = target.getAttribute("data-cx-tooltip");
    const r = target.getBoundingClientRect();
    cxTip.style.left = "0px";
    cxTip.style.top = "0px";
    cxTip.classList.add("is-visible");
    const w = cxTip.offsetWidth;
    cxTip.style.left = Math.max(8, Math.min(innerWidth - w - 8, r.left + r.width / 2 - w / 2)) + "px";
    cxTip.style.top = r.bottom + 8 + "px";
  };
  document.addEventListener("mouseover", (e) => {
    const t = e.target.closest("[data-cx-tooltip]");
    if (t) show(t);
    else cxTip.classList.remove("is-visible");
  });
  document.addEventListener("focusin", (e) => {
    const t = e.target.closest("[data-cx-tooltip]");
    if (t) show(t);
  });
  document.addEventListener("focusout", () => cxTip.classList.remove("is-visible"));
  document.addEventListener(
    "click",
    (e) => {
      if (e.target.closest(".cx-locked")) {
        e.preventDefault();
        e.stopPropagation();
      }
    },
    true
  );
}

