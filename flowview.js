export function indexFlow(roots) {
  const byId = new Map();
  const parentOf = new Map();
  const walk = (list, parent) => {
    for (const n of list) {
      byId.set(n.id, n);
      parentOf.set(n.id, parent);
      walk(n.children || [], n.id);
    }
  };
  walk(roots, null);
  return {byId, parentOf};
}

function treeItem(node, selectedId, onSelect, nodeCount) {
  const li = el("li", {attrs: {draggable: "false", "data-node-id": node.id}});
  const row = el("div", {cls: "flex-container"});
  const text = el("span", {cls: "node-text", text: node.name, attrs: {dir: "auto"}});
  row.appendChild(text);
  const meta = el("span", {cls: "node-inline-meta"});
  if (node.locked) meta.appendChild(el("span", {cls: "image-count self-count", attrs: {title: "Locked by the owner"}, children: [el("i", {cls: "fa-solid fa-lock", attrs: {"aria-hidden": "true"}})]}));
  if ((node.children || []).length) meta.appendChild(el("span", {cls: "child-count expanded", text: `[${node.children.length}]`, attrs: {title: "Child nodes"}}));
  row.appendChild(meta);
  row.appendChild(el("div", {cls: "arrow-container"}));
  li.appendChild(row);
  if (node.id === selectedId) li.classList.add("selected");
  row.addEventListener("click", (e) => {
    e.stopPropagation();
    onSelect(node.id);
  });
  if ((node.children || []).length) {
    const ul = el("ul");
    for (const c of node.children) ul.appendChild(treeItem(c, selectedId, onSelect));
    li.appendChild(ul);
  }
  return li;
}

export function renderTree(S, onSelect) {
  const tree = $("#tree");
  let ul = $("ul", tree);
  if (!ul) {
    ul = el("ul");
    tree.appendChild(ul);
  }
  ul.replaceChildren();
  for (const r of S.roots) ul.appendChild(treeItem(r, S.selectedId, onSelect));
  const title = $("#tree-title");
  if (title) title.value = S.flowName || "Shared Flow";
}

function pathTo(S, id) {
  const chain = [];
  for (let n = id; n; n = S.parentOf.get(n)) chain.unshift(n);
  return chain;
}

export function renderBreadcrumb(S) {
  const text = $(".breadcrumbs-text");
  if (!text) return;
  for (const e of $$(".breadcrumb-flow, .breadcrumb-separator, .breadcrumb-link, .breadcrumb-current-node", text)) e.remove();
  const anchor = $("#gallery-summary-btn", text);
  const tail = $(".breadcrumb-storage-figure", text);
  const put = (node) => text.insertBefore(node, tail || null);
  const flow = el("span", {cls: "breadcrumb-flow", text: S.flowName || "Shared Flow", attrs: {title: S.flowName || "Shared Flow"}});
  applyDeclarations(flow, "color: var(--accent-color); font-weight: bold;");
  put(flow);
  const chain = S.selectedId ? pathTo(S, S.selectedId) : [];
  chain.forEach((id, i) => {
    put(el("span", {cls: "breadcrumb-separator", text: "›"}));
    const n = S.byId.get(id);
    if (i === chain.length - 1) {
      const cur = el("span", {cls: "breadcrumb-current-node", text: n.name, attrs: {title: n.name, dir: "auto"}});
      applyDeclarations(cur, "font-weight: normal !important;");
      put(cur);
    } else put(el("span", {cls: "breadcrumb-link breadcrumb-main", text: n.name, attrs: {title: n.name, dir: "auto"}}));
  });
  void anchor;
}

// The notes of the selected node, as one card in the real slot-card markup. (Slots/media are T4c: the guest read carries
// no media, so the card shows the node's own title and notes.)
export function renderCard(S) {
  const gallery = $(".image-gallery");
  if (!gallery) return;
  const draft = $("textarea.image-notes", gallery);
  const dirty = !!(draft && draft.dataset.dirty === "1");
  const keep = dirty && draft.dataset.nodeId === S.selectedId ? draft.value : null;
  gallery.querySelectorAll(".enum-image-unit:not(.gs-media-unit)").forEach((u) => u.remove()); // G3: media cards are kept (media.js reconciles them)
  gallery.style.transform = "none";
  const node = S.selectedId ? S.byId.get(S.selectedId) : null;
  hideEl($("#gallery-top-scrubber")); // the slot scrubber navigates media slots (T4c); the demo ticks must not show
  hideEl($("#gallery-top-scrubber-spacer"));
  if (!node || !unitTemplate) return;
  const canType = S.role === "edit" && !node.locked && !S.offline;
  const u = unitTemplate.cloneNode(true);
  for (const a of ["data-canvas-notes-sized-for-width", "data-canvas-slot-height", "data-canvas-slot-width", "data-canvas-rendered-height"]) u.removeAttribute(a);
  u.setAttribute("data-canvas-placed", "1"); // the app hides a canvas card until it is marked placed
  u.style.left = "32px";
  u.style.top = "196px";
  u.setAttribute("data-node-id", node.id);
  for (const sel of [".canvas-image-number", ".add-image-position", ".image-stack-container", ".gallery-tag-section", ".canvas-connect-handle", ".canvas-resize-handle", ".canvas-slot-title-drag-strip", ".canvas-slot-drag-grip", ".gallery-notes-hide-from-joe", ".gallery-notes-target-toggle", ".image-notes-content"]) u.querySelectorAll(sel).forEach((x) => x.remove());
  const title = $(".image-title", u);
  if (title) {
    for (const a of [...title.attributes]) if (a.name.startsWith("data-")) title.removeAttribute(a.name); // they carry the snapshot's demo title
    title.value = node.name;
    title.setAttribute("value", node.name);
    if (canType) title.removeAttribute("readonly");
    else title.setAttribute("readonly", "");
  }
  const label = $(".gallery-notes-titlebar-label", u);
  if (label) label.textContent = "Notes";
  const ta = $("textarea.image-notes", u);
  if (ta) {
    for (const a of [...ta.attributes]) if (a.name.startsWith("data-")) ta.removeAttribute(a.name); // demo notes live in data-notes-undo-prev-value
    ta.classList.remove("gallery-notes-tiptap-source-masked");
    ta.textContent = node.notes || ""; // the snapshot's demo notes are the textarea's child text; replace it
    ta.value = keep !== null ? keep : node.notes || "";
    ta.dataset.nodeId = node.id;
    ta.dataset.field = "notes";
    ta.rows = 6;
    ta.style.height = "auto";
    ta.style.minHeight = "9em";
    ta.style.textAlign = "start";
    if (keep !== null) ta.dataset.dirty = "1";
    if (!canType) ta.setAttribute("readonly", "");
    else ta.removeAttribute("readonly");
  }
  const col = $(".image-notes-column", u);
  if (col) col.classList.remove("gallery-notes-tiptap-host");
  if (node.locked && col) {
    const note = el("div", {cls: "cx-locked-note", attrs: {"data-locked-note": "1"}});
    note.appendChild(el("i", {cls: "fa-solid fa-lock", attrs: {"aria-hidden": "true"}}));
    note.appendChild(document.createTextNode(`Locked by ${S.ownerName ? iso(S.ownerName) : "the owner"}`));
    col.after(note);
  }
  gallery.appendChild(u);
}

function agoText(at) {
  const min = Math.floor((Date.now() - at) / 60000);
  return min < 1 ? "just now" : min < 60 ? `${min} min ago` : `${Math.floor(min / 60)} h ago`;
}

export function renderChrome(S) {
  const n = S.byId.size;
  const stats = $(".status-footer-stats .status-footer-text");
  if (stats) stats.textContent = `${n} shared node${n === 1 ? "" : "s"}`;
  const save = $(".status-footer-save .status-footer-text");
  if (save) save.textContent = S.offline ? `Offline \u00b7 last synced ${agoText(S.lastSynced)}` : `Synced to ${S.ownerName ? iso(S.ownerName) + "'s" : "the owner's"} FlowJoe`;
  const kbd = $(".status-footer-save .status-footer-kbd");
  if (kbd) kbd.style.display = "none";
  const dot = $(".status-footer-save .status-footer-dot");
  if (dot) dot.style.background = S.offline ? "var(--danger-color)" : "var(--success-color)";
  $(".status-footer-save")?.classList.remove("is-dirty");
  const th = $(".status-footer-theme .status-footer-text");
  if (th) th.textContent = THEMES[S.themeId].name + " · shared";
}

